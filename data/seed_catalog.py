def seed_large_catalog():
    """Populate full e-commerce catalog idempotently without duplicate records."""
    try:
        # 1. Upsert Categories
        cat_map = {}
        for cat_info in CATEGORIES:
            cat = Category.query.filter_by(name=cat_info["name"]).first()
            if not cat:
                cat = Category(name=cat_info["name"], description=cat_info["description"])
                db.session.add(cat)
                db.session.flush()
            cat_map[cat_info["name"]] = cat.id

        # 2. Combine all products
        all_products = KURTI_CATALOG + OTHER_CATEGORIES_CATALOG

        # 3. Seed / Upsert Products safely by SKU or name
        for pdata in all_products:
            sku = pdata.get("sku")
            name = pdata.get("name")
            cat_name = pdata.get("category")
            cat_id = cat_map.get(cat_name)

            if not cat_id:
                continue

            existing = None
            if sku:
                existing = Product.query.filter_by(sku=sku).first()
            if not existing:
                existing = Product.query.filter_by(name=name).first()

            # Prepare specifications JSON
            specs = {
                "Fabric": pdata.get("fabric", ""),
                "Pattern": pdata.get("pattern", ""),
                "Occasion": pdata.get("occasion", ""),
                "Fit": pdata.get("fit", ""),
                "Sleeve Type": pdata.get("sleeve_type", ""),
                "Neck Type": pdata.get("neck_type", ""),
                "Brand": pdata.get("brand", ""),
            }
            # Clean up empty specs
            specs = {k: v for k, v in specs.items() if v}

            sizes_json = json.dumps(pdata.get("sizes", []))
            colors_json = json.dumps(pdata.get("colors", []))
            tags_json = json.dumps(pdata.get("tags", []))
            specs_json = json.dumps(specs)

            if existing:
                # Update existing record with enhanced fields
                existing.slug = pdata.get("slug", existing.slug)
                existing.subcategory = pdata.get("subcategory", existing.subcategory)
                existing.brand = pdata.get("brand", existing.brand)
                existing.sale_price = pdata.get("sale_price", existing.sale_price)
                existing.discount_percentage = pdata.get("discount_percentage", existing.discount_percentage)
                existing.currency = "INR"
                existing.sizes_json = sizes_json
                existing.colors_json = colors_json
                existing.tags_json = tags_json
                existing.specifications_json = specs_json
                existing.is_featured = pdata.get("is_featured", existing.is_featured)
                existing.is_new = pdata.get("is_new", existing.is_new)
                existing.is_best_seller = pdata.get("is_best_seller", existing.is_best_seller)
                if not existing.stock or existing.stock <= 0:
                    existing.stock = pdata.get("stock", 25)
            else:
                prod = Product(
                    name=name,
                    slug=pdata.get("slug"),
                    description=pdata.get("description"),
                    price=pdata.get("price", 999.0),
                    sale_price=pdata.get("sale_price"),
                    discount_percentage=pdata.get("discount_percentage", 0),
                    currency="INR",
                    category_id=cat_id,
                    subcategory=pdata.get("subcategory"),
                    brand=pdata.get("brand"),
                    image=pdata.get("image", "👗"),
                    stock=pdata.get("stock", 30),
                    rating=pdata.get("rating", 4.5),
                    review_count=pdata.get("review_count", 50),
                    sku=sku,
                    sizes_json=sizes_json,
                    colors_json=colors_json,
                    specifications_json=specs_json,
                    tags_json=tags_json,
                    is_featured=pdata.get("is_featured", False),
                    is_new=pdata.get("is_new", False),
                    is_best_seller=pdata.get("is_best_seller", False),
                    is_active=True,
                )
                db.session.add(prod)

        db.session.commit()
        log_info(f"Successfully verified/seeded {len(all_products)} products across 7 categories")
        return True
    except Exception as e:
        db.session.rollback()
        log_error(f"Catalog seeding failed: {e}")
        return False
